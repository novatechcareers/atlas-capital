export type TranslationKey = keyof typeof translations.en;

export function getStoredLanguage(): Language {
  if (typeof window === 'undefined' || !languageHydrated) return 'en';
  return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'pt-BR' ? 'pt-BR' : 'en';
}

export function markLanguageHydrated() {
  languageHydrated = true;
}

export function setStoredLanguage(language: Language) {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  document.documentElement.lang = language === 'pt-BR' ? 'pt-BR' : 'en';
}

export function translate(language: Language, key: TranslationKey) {
  return translations[language][key];
}

