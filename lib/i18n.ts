export function formatLocalizedCurrency(amount: number, language: Language) {
  return new Intl.NumberFormat(language === 'pt-BR' ? 'pt-BR' : 'en-US', {
    style: 'currency',
    currency: language === 'pt-BR' ? 'BRL' : 'USD',
    maximumFractionDigits: 2,
  }).format(amount);
}